// Turns content/challenges/*.ts into supabase/seed.sql.
// The seed publishes the five sample challenges on consecutive UTC days starting the day it runs
// (Day 1 today), and adds their clearly labelled sample responses. Running it again updates the
// content without moving release dates or duplicating samples.
import { writeFileSync } from "node:fs";
import { seedChallenges } from "../content/index.ts";

const tag = "$seed$";
const lit = (v: unknown) => {
  const s = JSON.stringify(v);
  if (s.includes(tag)) throw new Error("content contains the dollar-quote tag");
  return `${tag}${s}${tag}::jsonb`;
};
const text = (s: string) => {
  if (s.includes(tag)) throw new Error("content contains the dollar-quote tag");
  return `${tag}${s}${tag}`;
};

const lines: string[] = [
  "-- Generated by scripts/build-seed.ts from content/challenges. Do not edit by hand: npm run seed:build",
  "begin;",
];
for (const c of seedChallenges) {
  const { samples, ...doc } = c;
  if (c.cards.length !== 5) throw new Error(`${c.slug}: needs five cards`);
  lines.push(
    `-- Day ${c.number}: ${c.title}`,
    `select public._save_challenge(${lit(doc)} || jsonb_build_object('id', (select id from public.challenges where slug = '${c.slug}')), null);`,
    `insert into public.challenge_schedule (release_date, challenge_id)`,
    `  select public.app_today() + ${c.number - 1}, id from public.challenges where slug = '${c.slug}'`,
    `  on conflict do nothing;`,
    `update public.challenges set status = 'published' where slug = '${c.slug}' and status = 'draft';`
  );
  samples.forEach((s, i) => {
    lines.push(
      `insert into public.community_responses (challenge_id, display_name, title, body, is_sample, selected_label, selected_position)`,
      `  select id, ${text(s.display_name)}, ${text(s.title)}, ${text(s.body)}, true, ${text(s.selected_label)}, ${i + 1}`,
      `  from public.challenges c where slug = '${c.slug}'`,
      `  and not exists (select 1 from public.community_responses r where r.challenge_id = c.id and r.is_sample and r.title = ${text(s.title)});`
    );
  });
}
lines.push("commit;", "");
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), lines.join("\n"));
console.log(`Wrote supabase/seed.sql (${seedChallenges.length} challenges)`);
