// Builds the public website (site/): copies Aim's colors, fonts, mark and book covers into
// site/assets/, renders PRIVACY.md as site/privacy.html (the Chrome Web Store needs a privacy policy at
// a public URL; this keeps the page and the file the same), and, with --preview, zips the extension
// into site/download/aim-preview.zip for testers until the store listing is live.
// tests/site.test.mjs checks the copies and the privacy page are current.
// Run: node tools/build-site.mjs [--preview]
import { copyFileSync, mkdirSync, readFileSync, writeFileSync, existsSync, rmSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
export const ASSETS = [["tokens.css", "tokens.css"], ["covers.css", "covers.css"], ["covers.js", "covers.js"],
  ["fonts/Inter-Regular.woff2", "fonts/Inter-Regular.woff2"], ["fonts/Inter-Medium.woff2", "fonts/Inter-Medium.woff2"],
  ["fonts/InterDisplay-SemiBold.woff2", "fonts/InterDisplay-SemiBold.woff2"], ["fonts/InterDisplay-Bold.woff2", "fonts/InterDisplay-Bold.woff2"], ["fonts/OFL.txt", "fonts/OFL.txt"],
  ["icons/mark.svg", "mark.svg"], ["icons/128.png", "icon.png"], ["icons/48.png", "icon-48.png"]];

const esc = s => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const slug = s => s.toLowerCase().replace(/<[^>]+>/g, "").replace(/[^a-z0-9 -]/g, "").trim().replace(/\s+/g, "-");
// Inline Markdown: code, bold, italics, links. The text is escaped first.
const inline = s => esc(s)
  .replace(/`([^`]+)`/g, "<code>$1</code>")
  .replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>")
  .replace(/(^|[\s(])_([^_]+)_(?=[\s.,;:)]|$)/g, "$1<em>$2</em>")
  .replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, (m, t, href) => `<a href="${href.replace(/"/g, "%22")}">${t}</a>`);

// Enough Markdown for PRIVACY.md: headings, paragraphs, lists (one level), tables.
export function markdown(md) {
  const out = [], lines = md.replace(/\r/g, "").split("\n");
  let para = [], list = null, table = null;
  const flush = () => {
    if (para.length) { out.push(`<p>${inline(para.join(" "))}</p>`); para = []; }
    if (list) { out.push(`<${list.tag}>${list.items.map(i => `<li>${inline(i)}</li>`).join("")}</${list.tag}>`); list = null; }
    if (table) {
      const [head, , ...rows] = table;
      const cells = r => r.replace(/^\||\|$/g, "").split("|").map(c => c.trim());
      out.push(`<div class="table"><table><thead><tr>${cells(head).map(c => `<th>${inline(c)}</th>`).join("")}</tr></thead><tbody>${rows.map(r => `<tr>${cells(r).map(c => `<td>${inline(c)}</td>`).join("")}</tr>`).join("")}</tbody></table></div>`);
      table = null;
    }
  };
  for (const line of lines) {
    let m;
    if (!line.trim()) { flush(); continue; }
    if ((m = line.match(/^(#{1,4})\s+(.*)$/))) { flush(); const n = m[1].length; out.push(`<h${n} id="${slug(m[2])}">${inline(m[2])}</h${n}>`); continue; }
    if (line.startsWith("|")) { if (!table) { flush(); table = []; } table.push(line); continue; }
    if ((m = line.match(/^\s*([-*]|\d+\.)\s+(.*)$/))) {
      const tag = /\d/.test(m[1]) ? "ol" : "ul";
      if (para.length || (list && list.tag !== tag)) flush();
      (list ||= { tag, items: [] }).items.push(m[2]);
      continue;
    }
    if (list && /^\s{2,}\S/.test(line)) { list.items[list.items.length - 1] += " " + line.trim(); continue; }
    if (list) flush();
    para.push(line.trim());
  }
  flush();
  return out.join("\n");
}

export function privacyPage() {
  const md = readFileSync(root + "PRIVACY.md", "utf8").replace(/^# .*\n/, "");
  return `<!doctype html>
<!-- GENERATED by tools/build-site.mjs from PRIVACY.md. Edit PRIVACY.md, then run the script. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="color-scheme" content="light dark">
<title>Privacy policy · Aim</title>
<meta name="description" content="How Aim, the Chrome extension for using YouTube on purpose, handles your data.">
<link rel="icon" href="assets/icon.png">
<link rel="stylesheet" href="assets/tokens.css">
<link rel="stylesheet" href="site.css">
</head>
<body class="doc">
<header class="top"><div class="wrap">
  <a class="brand" href="./"><img src="assets/mark.svg" alt="" width="28" height="28"><span>Aim</span></a>
  <nav aria-label="Main"><a href="./#how">How it works</a><a href="./#learn">Learning</a><a href="./#pricing">Pricing</a></nav>
</div></header>
<main class="wrap prose">
<p class="eyebrow">Aim</p>
<h1>Privacy policy</h1>
${markdown(md)}
</main>
<footer class="foot"><div class="wrap"><span>Aim is not affiliated with YouTube or Google.</span><a href="./">Home</a></div></footer>
</body>
</html>
`;
}

export const stale = () => [
  ...ASSETS.filter(([from, to]) => { try { return !readFileSync(root + from).equals(readFileSync(root + "site/assets/" + to)); } catch { return true; } }).map(([, to]) => "assets/" + to),
  ...((() => { try { return readFileSync(root + "site/privacy.html", "utf8") === privacyPage() ? [] : ["privacy.html"]; } catch { return ["privacy.html"]; } })())];

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  mkdirSync(root + "site/assets/fonts", { recursive: true });
  for (const [from, to] of ASSETS) copyFileSync(root + from, root + "site/assets/" + to);
  writeFileSync(root + "site/privacy.html", privacyPage());
  console.log(`Copied ${ASSETS.length} files into site/assets/ and wrote site/privacy.html.`);
  if (process.argv.includes("--preview")) {
    mkdirSync(root + "site/download", { recursive: true });
    const zip = root + "site/download/aim-preview.zip";
    if (existsSync(zip)) rmSync(zip);
    // What's committed, without tests, server code, docs, tools, the parent website or this site.
    execFileSync("git", ["archive", "--format=zip", "-o", zip, "HEAD", ":!tests", ":!supabase", ":!docs", ":!tools", ":!web", ":!site", ":!real-youtube-report"], { cwd: root });
    console.log("Wrote site/download/aim-preview.zip from the last commit.");
  }
}
