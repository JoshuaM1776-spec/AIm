// Builds supabase/functions/ai-dashboard.ts: the AI endpoint as one file, for pasting into
// Supabase's browser editor (Edge Functions → Deploy a new function → Via Editor).
// Run after changing handler.ts or index.ts: node tools/bundle-ai.mjs
import fs from "node:fs";
const dir = new URL("../supabase/functions/ai/", import.meta.url);
const handler = fs.readFileSync(new URL("handler.ts", dir), "utf8");
const index = fs.readFileSync(new URL("index.ts", dir), "utf8");
const importLine = /^import \{[^}]*\} from "\.\/handler\.ts";\n/m;
if (!importLine.test(index)) throw new Error("index.ts no longer imports ./handler.ts as expected");
const [imports, rest] = (() => {
  const body = index.replace(importLine, "");
  const lines = body.split("\n");
  const last = lines.findLastIndex(l => l.startsWith("import "));
  return [lines.slice(0, last + 1).join("\n"), lines.slice(last + 1).join("\n")];
})();
const out = `// GENERATED by tools/bundle-ai.mjs from supabase/functions/ai/handler.ts and index.ts. Don't edit by hand.
// Paste this whole file into Supabase's function editor for a function named "ai".
${imports}

// ---------- handler.ts ----------
${handler}
// ---------- index.ts ----------
${rest}`;
fs.writeFileSync(new URL("../supabase/functions/ai-dashboard.ts", import.meta.url), out);
console.log("wrote supabase/functions/ai-dashboard.ts");
